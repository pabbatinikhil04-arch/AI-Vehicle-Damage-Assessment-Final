def calculate_assessment(damage_area_percent):

    # Project-defined severity
    if damage_area_percent < 2:
        severity = "Low"
    elif damage_area_percent < 8:
        severity = "Moderate"
    elif damage_area_percent < 20:
        severity = "High"
    else:
        severity = "Severe"

    # Project-defined assessment score
    score = max(
        0,
        min(
            100,
            100 - (damage_area_percent * 3)
        )
    )

    # Project-defined eligibility
    if score >= 70:
        eligibility = "Eligible"
    else:
        eligibility = "Not Eligible"

    return severity, score, eligibility


def predict_vehicle_damage(
    image,
    classification_model,
    classification_model_name="Model"
):

    # --------------------------------------------------------
    # IMAGE
    # --------------------------------------------------------

    if isinstance(image, np.ndarray):
        image = Image.fromarray(image)

    image = image.convert("RGB")

    # --------------------------------------------------------
    # CLASSIFICATION
    # --------------------------------------------------------

    cls_input = classification_transform(
        image
    ).unsqueeze(0).to(device)

    classification_model.eval()

    with torch.no_grad():

        logits = classification_model(
            cls_input
        )

        probabilities = torch.softmax(
            logits,
            dim=1
        )

        confidence, predicted_class = torch.max(
            probabilities,
            dim=1
        )

    class_index = predicted_class.item()

    damage_type = CLASS_NAMES[class_index]

    confidence_value = confidence.item() * 100

    # --------------------------------------------------------
    # SEGMENTATION
    # --------------------------------------------------------

    seg_input = segmentation_transform(
        image
    ).unsqueeze(0).to(device)

    with torch.no_grad():

        seg_logits = seg_model(
            seg_input
        )

        seg_probability = torch.sigmoid(
            seg_logits
        )

        seg_mask = (
            seg_probability >= 0.60
        ).float()

    # --------------------------------------------------------
    # DAMAGE AREA
    # --------------------------------------------------------

    damaged_pixels = seg_mask.sum().item()

    total_pixels = (
        seg_mask.shape[-1]
        * seg_mask.shape[-2]
    )

    damage_area_percent = (
        damaged_pixels
        / total_pixels
    ) * 100

    # --------------------------------------------------------
    # ASSESSMENT
    # --------------------------------------------------------

    severity, score, eligibility = (
        calculate_assessment(
            damage_area_percent
        )
    )

    return {
        "model": classification_model_name,
        "damage_type": damage_type,
        "classification_confidence": round(
            confidence_value, 2
        ),
        "damage_area_percent": round(
            damage_area_percent, 2
        ),
        "severity": severity,
        "assessment_score": round(
            score, 2
        ),
        "insurance_eligibility": eligibility,
        "segmentation_mask": seg_mask
            .squeeze()
            .cpu()
            .numpy()
    }


