    image = Image.open(image_path).convert("RGB")

    # Classification
    classifier.eval()

    classification_tensor = classification_transform(
        image
    ).unsqueeze(0).to(device)

    with torch.inference_mode():

        class_logits = classifier(
            classification_tensor
        )

        probabilities = torch.softmax(
            class_logits, dim=1
        )[0]

        predicted_index = int(
            torch.argmax(probabilities).item()
        )

        confidence = float(
            probabilities[predicted_index].item()
        ) * 100.0

    predicted_class = idx_to_class[predicted_index]

    # Segmentation — common model for both versions
    segmentation_model.eval()

    segmentation_tensor = segmentation_transform(
        image
    ).unsqueeze(0).to(device)

    with torch.inference_mode():

        segmentation_logits = segmentation_model(
            segmentation_tensor
        )

        damage_probability = torch.sigmoid(
            segmentation_logits
        )

        binary_mask = (
            damage_probability >= SEGMENTATION_THRESHOLD
        )

    # Count mask pixels at the 256 x 256 output resolution.
    mask_pixels = int(binary_mask[0, 0].sum().item())

    total_pixels = int(
        binary_mask.shape[-2] * binary_mask.shape[-1]
    )

    damage_percentage = (
        mask_pixels / total_pixels
    ) * 100.0

    (
        severity,
        assessment_score,
        assessment_category,
        insurance_status
    ) = calculate_assessment(
        damage_percentage,
        confidence
    )

    return {
        "predicted_damage_type": predicted_class,
        "classification_confidence": confidence,
        "damage_area_percent": damage_percentage,
        "severity": severity,
        "assessment_score": assessment_score,
        "assessment_category": assessment_category,
        "insurance_status": insurance_status
    }

