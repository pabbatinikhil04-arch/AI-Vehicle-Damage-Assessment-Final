class DoubleConv(nn.Module):
    def __init__(self, in_channels, out_channels):
        super().__init__()
        self.block = nn.Sequential(
            nn.Conv2d(in_channels, out_channels, 3, padding=1),
            nn.BatchNorm2d(out_channels),
            nn.ReLU(inplace=True),
            nn.Conv2d(out_channels, out_channels, 3, padding=1),
            nn.BatchNorm2d(out_channels),
            nn.ReLU(inplace=True)
        )

    def forward(self, x):
        return self.block(x)


class UNetResNet18Exact(nn.Module):
    def __init__(self):
        super().__init__()
        backbone = models.resnet18(weights=None)

        self.encoder0 = nn.Sequential(
            backbone.conv1, backbone.bn1, backbone.relu
        )
        self.pool = backbone.maxpool
        self.encoder1 = backbone.layer1
        self.encoder2 = backbone.layer2
        self.encoder3 = backbone.layer3
        self.encoder4 = backbone.layer4

        self.up4 = nn.ConvTranspose2d(512, 256, 2, 2)
        self.conv4 = DoubleConv(512, 256)

        self.up3 = nn.ConvTranspose2d(256, 128, 2, 2)
        self.conv3 = DoubleConv(256, 128)

        self.up2 = nn.ConvTranspose2d(128, 64, 2, 2)
        self.conv2 = DoubleConv(128, 64)

        self.up1 = nn.ConvTranspose2d(64, 64, 2, 2)
        self.conv1 = DoubleConv(128, 64)

        self.up0 = nn.ConvTranspose2d(64, 32, 2, 2)
        self.conv0 = DoubleConv(32, 32)

        self.final = nn.Conv2d(32, 1, 1)

    def forward(self, x):
        e0 = self.encoder0(x)
        e1 = self.encoder1(self.pool(e0))
        e2 = self.encoder2(e1)
        e3 = self.encoder3(e2)
        e4 = self.encoder4(e3)

        d4 = self.conv4(torch.cat([self.up4(e4), e3], dim=1))
        d3 = self.conv3(torch.cat([self.up3(d4), e2], dim=1))
        d2 = self.conv2(torch.cat([self.up2(d3), e1], dim=1))
        d1 = self.conv1(torch.cat([self.up1(d2), e0], dim=1))
        d0 = self.up0(d1)

        return self.final(d0)


