def calculate_assessment(damage_percentage, confidence_percentage):
    if damage_percentage < 5:
        severity = "Low"
    elif damage_percentage < 15:
        severity = "Moderate"
    elif damage_percentage < 30:
        severity = "High"
    else:
        severity = "Very High"

    score = np.clip(
        0.60 * damage_percentage + 0.40 * confidence_percentage,
        0, 100
    )

    if score < 25:
        category = "Low Assessment"
    elif score < 50:
        category = "Moderate Assessment"
    elif score < 75:
        category = "High Assessment"
    else:
        category = "Very High Assessment"

    eligibility = (
        "Insurance Eligible"
        if score >= 25
        else "Not Insurance Eligible"
    )

    return severity, float(score), category, eligibility

