def preprocess(image, method):
    image = image.convert("RGB")

    if method == "direct_resize":
        image = image.resize((224, 224), Image.Resampling.BILINEAR)

    elif method == "center_crop":
        width, height = image.size
        scale = 224 / min(width, height)
        new_size = (round(width * scale), round(height * scale))

        image = image.resize(new_size, Image.Resampling.BILINEAR)

        left = (image.width - 224) // 2
        top = (image.height - 224) // 2
        image = image.crop((left, top, left + 224, top + 224))

    elif method == "padding":
        width, height = image.size
        scale = 224 / max(width, height)
        new_size = (
            max(1, round(width * scale)),
            max(1, round(height * scale))
        )

        image = image.resize(new_size, Image.Resampling.BILINEAR)

        canvas = Image.new("RGB", (224, 224), (128, 128, 128))
        left = (224 - image.width) // 2
        top = (224 - image.height) // 2
        canvas.paste(image, (left, top))
        image = canvas

    tensor = transforms.ToTensor()(image)
    return normalize(tensor).unsqueeze(0)

