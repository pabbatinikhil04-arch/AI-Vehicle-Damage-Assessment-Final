    train_samples = 0

    for images, labels in train_loader:
        images = images.to(device, non_blocking=True)
        labels = labels.to(device, non_blocking=True)

        optimizer.zero_grad(set_to_none=True)

        logits = model(images)
        loss = criterion(logits, labels)

        loss.backward()
        optimizer.step()

        train_loss_sum += loss.item() * labels.size(0)
        train_samples += labels.size(0)

    train_loss = train_loss_sum / train_samples

    model.eval()
    val_loss_sum = 0.0
    val_samples = 0
    y_true, y_pred = [], []

    with torch.inference_mode():
        for images, labels in val_loader:
            images = images.to(device, non_blocking=True)
            labels = labels.to(device, non_blocking=True)

            logits = model(images)
            loss = criterion(logits, labels)

            val_loss_sum += loss.item() * labels.size(0)
            val_samples += labels.size(0)

            predictions = logits.argmax(dim=1)
            y_true.extend(labels.cpu().tolist())
            y_pred.extend(predictions.cpu().tolist())

    val_loss = val_loss_sum / val_samples
    val_accuracy = accuracy_score(y_true, y_pred)
    val_macro_f1 = f1_score(
        y_true, y_pred,
        labels=list(range(NUM_CLASSES)),
        average="macro",
        zero_division=0
    )
    val_weighted_f1 = f1_score(
        y_true, y_pred,
        average="weighted",
        zero_division=0
    )
    val_macro_recall = recall_score(
        y_true, y_pred,
        labels=list(range(NUM_CLASSES)),
        average="macro",
        zero_division=0
    )

    row = {
        "epoch": epoch,
        "train_loss": train_loss,
        "validation_loss": val_loss,
        "validation_accuracy_pct": 100 * val_accuracy,
        "validation_macro_f1_pct": 100 * val_macro_f1,
        "validation_weighted_f1_pct": 100 * val_weighted_f1,
        "validation_macro_recall_pct": 100 * val_macro_recall
    }

