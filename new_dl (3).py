class DoubleConv(nn.Module):

    def __init__(
        self,
        in_channels,
        out_channels
    ):

        super().__init__()

        self.block = nn.Sequential(

            nn.Conv2d(
                in_channels,
                out_channels,
                kernel_size=3,
                padding=1,
                bias=True
            ),

            nn.BatchNorm2d(
                out_channels
            ),

            nn.ReLU(
                inplace=True
            ),

            nn.Conv2d(
                out_channels,
                out_channels,
                kernel_size=3,
                padding=1,
                bias=True
            ),

            nn.BatchNorm2d(
                out_channels
            ),

            nn.ReLU(
                inplace=True
            )
        )

    def forward(self, x):

        return self.block(x)


# ============================================================
# 4. EXACT CHECKPOINT ARCHITECTURE
#
# Checkpoint keys:
#
# encoder0
# encoder1
# encoder2
# encoder3
# encoder4
#
# up4 + conv4
# up3 + conv3
# up2 + conv2
# up1 + conv1
# up0 + conv0
#
# final
# ============================================================

class UNetResNet18Exact(nn.Module):

    def __init__(self):

        super().__init__()


        # ----------------------------------------------------
        # RESNET18 ENCODER
        # ----------------------------------------------------

        resnet = models.resnet18(
            weights=None
        )


        self.encoder0 = nn.Sequential(
            resnet.conv1,
            resnet.bn1,
            resnet.relu
        )

        self.pool = resnet.maxpool

        self.encoder1 = resnet.layer1
        self.encoder2 = resnet.layer2
        self.encoder3 = resnet.layer3
        self.encoder4 = resnet.layer4


        # ----------------------------------------------------
        # DECODER 4
        # ----------------------------------------------------

        self.up4 = nn.ConvTranspose2d(
            512,
            256,
            kernel_size=2,
            stride=2
        )

        self.conv4 = DoubleConv(
            512,
            256
        )


        # ----------------------------------------------------
        # DECODER 3
        # ----------------------------------------------------

        self.up3 = nn.ConvTranspose2d(
            256,
            128,
            kernel_size=2,
            stride=2
        )

        self.conv3 = DoubleConv(
            256,
            128
        )


        # ----------------------------------------------------
        # DECODER 2
        # ----------------------------------------------------

        self.up2 = nn.ConvTranspose2d(
            128,
            64,
            kernel_size=2,
            stride=2
        )

        self.conv2 = DoubleConv(
            128,
            64
        )


        # ----------------------------------------------------
        # DECODER 1
        # ----------------------------------------------------

        self.up1 = nn.ConvTranspose2d(
            64,
            64,
            kernel_size=2,
            stride=2
        )

        self.conv1 = DoubleConv(
            128,
            64
        )


        # ----------------------------------------------------
        # FINAL UPSAMPLING
        # ----------------------------------------------------

        self.up0 = nn.ConvTranspose2d(
            64,
            32,
            kernel_size=2,
            stride=2
        )

        # IMPORTANT:
        # Checkpoint says:
        # conv0.block.0.weight = [32, 32, 3, 3]
        #
        # Therefore conv0 input MUST be 32.
        # There is NO concatenation here.

        self.conv0 = DoubleConv(
            32,
            32
        )


        # ----------------------------------------------------
        # FINAL OUTPUT
        # ----------------------------------------------------

        self.final = nn.Conv2d(
            32,
            1,
            kernel_size=1
        )


    # ========================================================
    # FORWARD
    # ========================================================

    def forward(self, x):


        # ----------------------------------------------------
        # ENCODER
        # ----------------------------------------------------

        e0 = self.encoder0(x)

        e1 = self.encoder1(
            self.pool(e0)
        )

        e2 = self.encoder2(e1)

        e3 = self.encoder3(e2)

        e4 = self.encoder4(e3)


        # ----------------------------------------------------
        # DECODER 4
        # ----------------------------------------------------

        d4 = self.up4(e4)

        if d4.shape[-2:] != e3.shape[-2:]:

            d4 = F.interpolate(
                d4,
                size=e3.shape[-2:],
                mode="bilinear",
                align_corners=False
            )

        d4 = torch.cat(
            [d4, e3],
            dim=1
        )

        d4 = self.conv4(d4)


        # ----------------------------------------------------
        # DECODER 3
        # ----------------------------------------------------

        d3 = self.up3(d4)

        if d3.shape[-2:] != e2.shape[-2:]:

            d3 = F.interpolate(
                d3,
                size=e2.shape[-2:],
                mode="bilinear",
                align_corners=False
            )

        d3 = torch.cat(
            [d3, e2],
            dim=1
        )

        d3 = self.conv3(d3)


        # ----------------------------------------------------
        # DECODER 2
        # ----------------------------------------------------

        d2 = self.up2(d3)

        if d2.shape[-2:] != e1.shape[-2:]:

            d2 = F.interpolate(
                d2,
                size=e1.shape[-2:],
                mode="bilinear",
                align_corners=False
            )

        d2 = torch.cat(
            [d2, e1],
            dim=1
        )

        d2 = self.conv2(d2)


        # ----------------------------------------------------
        # DECODER 1
        # ----------------------------------------------------

        d1 = self.up1(d2)

        if d1.shape[-2:] != e0.shape[-2:]:

            d1 = F.interpolate(
                d1,
                size=e0.shape[-2:],
                mode="bilinear",
                align_corners=False
            )

        d1 = torch.cat(
            [d1, e0],
            dim=1
        )

        d1 = self.conv1(d1)


        # ----------------------------------------------------
        # FINAL DECODER
        # ----------------------------------------------------

        d0 = self.up0(d1)

        if d0.shape[-2:] != x.shape[-2:]:

            d0 = F.interpolate(
                d0,
                size=x.shape[-2:],
                mode="bilinear",
                align_corners=False
            )

        # NO CONCATENATION HERE
        d0 = self.conv0(d0)


        # ----------------------------------------------------
        # FINAL MASK
        # ----------------------------------------------------

        out = self.final(d0)

        return out


