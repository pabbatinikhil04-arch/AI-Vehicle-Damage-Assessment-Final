def get_image_id(filename):
    """Extract numeric ID from names such as 165.jpeg or internal_test_01_ID_165.jpg."""
    stem = Path(filename).stem

    match = re.search(r"_ID_(\d+)$", stem, re.IGNORECASE)
    if match:
        return match.group(1)

    if stem.isdigit():
        return stem

    return None

def image_info(path):
    try:
        with Image.open(path) as im:
            width, height = im.size
            rgb = im.convert("RGB")
            rgb.thumbnail((224, 224))
            pixels = np.asarray(rgb, dtype=np.uint8)

        digest = hashlib.sha256(Path(path).read_bytes()).hexdigest()

        return {
            "path": str(path),
            "width": width,
            "height": height,
            "sha256": digest,
            "thumbnail_mean_rgb": np.round(
                pixels.reshape(-1, 3).mean(axis=0), 2
            ).tolist()
        }
    except Exception:
        return None

